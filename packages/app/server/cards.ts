export function forbiddenClues(word: string, difficulty: Difficulty): string[] {
  const count = { easy: 0, medium: 2, hard: 4 }[difficulty];
  const clues = clueCards[word];
  if (!clues) throw new Error(`Missing BAIT card: ${word}`);
  return clues.slice(0, count);
}
